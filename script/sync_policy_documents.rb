#!/usr/bin/env ruby
# Canonical sources stay at repository root/docs; these are bundled projections.
require 'fileutils'
require 'pathname'
require 'digest'

module PolicyDocuments
  SOURCES = {
    'privacy.md' => 'docs/legal/privacy.md',
    'terms.md' => 'docs/legal/terms.md',
    'security.md' => 'SECURITY.md',
    'notices.md' => 'THIRD_PARTY_NOTICES.md',
    'license.md' => 'LICENSE'
  }.freeze
  DESTINATION = 'apps/macos/Sources/OpenScribeApp/Resources/Policies'.freeze
  DIGESTS = 'apps/macos/Sources/OpenScribeApp/Generated/PolicyDocumentDigests.swift'.freeze

  def self.sync(root, check:)
    root = Pathname.new(root).realpath
    destination = root.join(DESTINATION)
    # Refuse redirected source or output components, including parent directories.
    paths = SOURCES.values + [DESTINATION, DIGESTS] + SOURCES.keys.map { |name| "#{DESTINATION}/#{name}" }
    paths.each do |relative|
      current = root
      Pathname.new(relative).each_filename do |part|
        current = current.join(part)
        raise "symlinked policy path: #{relative}" if current.symlink?
      end
    end
    expected = SOURCES.to_h do |name, source|
      path = root.join(source)
      raise "missing canonical policy: #{source}" unless path.file?
      bytes = path.binread
      raise "invalid policy text: #{source}" unless bytes.dup.force_encoding('UTF-8').valid_encoding? && !bytes.empty?
      [name, bytes]
    end
    if destination.exist?
      raise 'policy destination is not a directory' unless destination.directory?
      unexpected = destination.children.map { |path| path.basename.to_s } - SOURCES.keys
      raise "unexpected bundled policy files: #{unexpected.join(', ')}" unless unexpected.empty?
    end
    if check
      expected.each do |name, bytes|
        path = destination.join(name)
        raise "bundled policy drift: #{name}; run script/sync_policy_documents.rb" unless path.file? && path.binread == bytes
      end
    else
      FileUtils.mkdir_p(destination)
      expected.each do |name, bytes|
        path = destination.join(name)
        next if path.file? && path.binread == bytes
        # The destination is generated source, never a library or release output.
        path.binwrite(bytes)
      end
    end
    digests = "// Generated by script/sync_policy_documents.rb. Edit canonical sources.\nenum PolicyDocumentDigests {\n  static let sha256: [String: String] = [\n"
    expected.each do |name, bytes|
      digests << "    \"#{File.basename(name, '.md')}\": \"#{Digest::SHA256.hexdigest(bytes)}\",\n"
    end
    digests << "  ]\n}\n"
    digest_path = root.join(DIGESTS)
    if check
      raise 'compiled policy digest drift; run script/sync_policy_documents.rb' unless digest_path.file? && digest_path.binread == digests.b
    else
      FileUtils.mkdir_p(digest_path.dirname)
      digest_path.binwrite(digests)
    end
  end
end

if $PROGRAM_NAME == __FILE__
  unless ARGV.empty? || ARGV == ['--check']
    warn 'usage: script/sync_policy_documents.rb [--check]'
    exit 64
  end
  begin
    PolicyDocuments.sync(File.expand_path('..', __dir__), check: ARGV == ['--check'])
    puts(ARGV.empty? ? 'POLICY_DOCUMENTS_SYNCED' : 'POLICY_DOCUMENTS_CURRENT')
  rescue StandardError => error
    warn "POLICY_DOCUMENTS_RED: #{error.message}"
    exit 1
  end
end
